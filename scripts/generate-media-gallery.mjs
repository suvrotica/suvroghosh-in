import { stat, readFile, readdir, mkdir, rename, writeFile } from 'node:fs/promises';
import { dirname, extname, relative, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const manifestPath = resolve(root, 'scripts', 'image-optimization-manifest.json');
const galleryOutputPath = resolve(root, 'src', 'lib', 'generated', 'media-gallery.ts');
const dimensionsOutputPath = resolve(
	root,
	'src',
	'lib',
	'server',
	'generated',
	'image-dimensions.js'
);
const verifyOnly = process.env.VERCEL === '1' || process.env.IMAGE_OPTIMIZE_VERIFY_ONLY === '1';
const supportedExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp']);
const sources = [
	{ key: 'images', directory: 'images', publicDirectory: 'images' },
	{ key: 'photos', directory: 'photos', publicDirectory: 'photos' },
	{ key: 'thumbnails', directory: 'thumbnail', publicDirectory: 'thumbnail' }
];

function toPosix(value) {
	return value.split(sep).join('/');
}

function publicPath(directory, relativePath) {
	return `/${[directory, ...relativePath.split('/')].map(encodeURIComponent).join('/')}`;
}

async function collectFiles(directory) {
	const entries = await readdir(directory, { withFileTypes: true });
	const files = [];
	for (const entry of entries) {
		const path = resolve(directory, entry.name);
		if (entry.isDirectory()) files.push(...(await collectFiles(path)));
		else if (entry.isFile() && supportedExtensions.has(extname(entry.name).toLowerCase())) {
			files.push(path);
		}
	}
	return files;
}

async function loadOptimizationManifest() {
	try {
		const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
		return manifest.files ?? {};
	} catch (error) {
		if (error?.code === 'ENOENT') return {};
		throw error;
	}
}

async function writeIfChanged(path, contents, label) {
	try {
		if ((await readFile(path, 'utf8')) === contents) return false;
	} catch (error) {
		if (error?.code !== 'ENOENT') throw error;
	}
	if (verifyOnly) {
		throw new Error(
			`${label} is missing or stale. Run \`npm run gallery:generate\` and commit the result.`
		);
	}

	await mkdir(dirname(path), { recursive: true });
	const temporaryPath = `${path}.${process.pid}.tmp`;
	await writeFile(temporaryPath, contents, 'utf8');
	await rename(temporaryPath, path);
	return true;
}

const optimizationManifest = await loadOptimizationManifest();
const gallery = {};
const dimensionsByPath = {};

for (const source of sources) {
	const directory = resolve(root, 'static', source.directory);
	const files = await collectFiles(directory);
	files.sort((left, right) =>
		toPosix(relative(directory, left)).localeCompare(toPosix(relative(directory, right)), 'en', {
			numeric: true,
			sensitivity: 'base'
		})
	);

	gallery[source.key] = await Promise.all(
		files.map(async (path) => {
			const relativePath = toPosix(relative(directory, path));
			const repositoryPath = `static/${source.directory}/${relativePath}`;
			const metadata = optimizationManifest[repositoryPath] ?? {};
			const fileStats = await stat(path);
			const width = Number.isInteger(metadata.width) && metadata.width > 0 ? metadata.width : null;
			const height =
				Number.isInteger(metadata.height) && metadata.height > 0 ? metadata.height : null;
			if (width === null || height === null) {
				throw new Error(
					`${repositoryPath} has no valid dimensions in scripts/image-optimization-manifest.json.`
				);
			}
			const src = publicPath(source.publicDirectory, relativePath);
			return {
				name: relativePath,
				src,
				bytes: fileStats.size,
				width,
				height
			};
		})
	);
	for (const asset of gallery[source.key]) {
		dimensionsByPath[asset.src] = [asset.width, asset.height];
	}
}

const source = `// Generated by scripts/generate-media-gallery.mjs. Do not edit by hand.\n\nexport type MediaGalleryTab = 'images' | 'photos' | 'thumbnails';\n\nexport interface MediaGalleryAsset {\n\tname: string;\n\tsrc: string;\n\tbytes: number;\n\twidth: number | null;\n\theight: number | null;\n}\n\nexport const mediaGallery: Record<MediaGalleryTab, MediaGalleryAsset[]> = ${JSON.stringify(gallery, null, '\t')};\n`;
const dimensionsSource = `// Generated by scripts/generate-media-gallery.mjs. Do not edit by hand.\n\n/** @type {Readonly<Record<string, Readonly<[number, number]>>>} */\nexport const imageDimensionsByPath = ${JSON.stringify(dimensionsByPath)};\n`;
const galleryChanged = await writeIfChanged(galleryOutputPath, source, 'Media gallery');
const dimensionsChanged = await writeIfChanged(
	dimensionsOutputPath,
	dimensionsSource,
	'Image dimensions map'
);
const counts = sources.map(({ key }) => `${key}: ${gallery[key].length}`).join(', ');
console.log(`${galleryChanged ? 'Generated' : 'Verified'} media gallery (${counts}).`);
console.log(
	`${dimensionsChanged ? 'Generated' : 'Verified'} server image dimensions (${Object.keys(dimensionsByPath).length} assets).`
);
