import fs from 'node:fs';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = process.cwd();
const postsDirectory = path.join(root, 'src', 'lib', 'posts');
const outputPath = path.join(root, 'src', 'lib', 'generated', 'music-posts.ts');

function splitPost(rawText) {
	const match = rawText.match(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)([\s\S]*)$/);
	return match?.[1] ?? rawText;
}

function isMusicVideoSource(value) {
	const source = value.trim().split(/[?#]/, 1)[0].replaceAll('\\', '/');
	return /^(?:\/videos\/)?music\/.+\.mp4$/i.test(source);
}

function containsMusicVideo(body) {
	const mediaElement = /<(?:Vid|PostVideo|video)\b[\s\S]*?>/gi;
	const sourceAttribute = /\bsrc\s*=\s*(["'])([^"']+)\1/i;

	for (const match of body.matchAll(mediaElement)) {
		const source = sourceAttribute.exec(match[0])?.[2];
		if (source && isMusicVideoSource(source)) return true;
	}

	return false;
}

const postFiles = fs
	.readdirSync(postsDirectory, { withFileTypes: true })
	.filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.md'))
	.map((entry) => entry.name)
	.sort((left, right) => left.localeCompare(right, 'en'));

const musicPostSlugs = postFiles.flatMap((filename) => {
	const source = fs.readFileSync(path.join(postsDirectory, filename), 'utf8');
	return containsMusicVideo(splitPost(source)) ? [filename.replace(/\.md$/i, '')] : [];
});

const source = `// Generated by scripts/generate-music-posts.mjs. Do not edit by hand.\nexport const musicPostSlugs = ${JSON.stringify(musicPostSlugs)} as const;\n`;
const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const output = await format(source, { ...prettierConfig, parser: 'typescript' });
const previousOutput = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';

if (previousOutput === output) {
	console.log(
		`Music topic: scanned ${postFiles.length}, matched ${musicPostSlugs.length}, manifest unchanged.`
	);
} else {
	fs.mkdirSync(path.dirname(outputPath), { recursive: true });
	fs.writeFileSync(outputPath, output, 'utf8');
	console.log(
		`Music topic: scanned ${postFiles.length}, matched ${musicPostSlugs.length}, manifest updated.`
	);
}
